# Runs the real src modules in a real Luau VM against tests/spec.luau.
#   powershell -ExecutionPolicy Bypass -File run-tests.ps1
#
# Needs the Luau CLI (https://github.com/luau-lang/luau/releases).
# Set LUAU_EXE to override discovery.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$tests = Join-Path $root 'tests'

# ---- locate luau ------------------------------------------------------
$luau = $env:LUAU_EXE
if (-not $luau -or -not (Test-Path $luau)) {
  $onPath = Get-Command luau -ErrorAction SilentlyContinue
  if ($onPath) {
    $luau = $onPath.Source
  } elseif (Test-Path "$env:USERPROFILE\tools\luau\luau.exe") {
    $luau = "$env:USERPROFILE\tools\luau\luau.exe"
  } else {
    throw "luau.exe not found. Install it from https://github.com/luau-lang/luau/releases (luau-windows.zip) and either put it on PATH or set LUAU_EXE."
  }
}

# ---- modules under test ----------------------------------------------
# Only modules that load without a live Roblox client. 35/40/50/60 need
# services this stub does not pretend to provide.
$modules = @(
  '00_boot.lua'
  '10_caps.lua'
  '12_keymap.lua'
  '15_input.lua'
  '20_move.lua'
  '25_world.lua'
  '30_act.lua'
)

$parts = New-Object System.Collections.Generic.List[string]
$parts.Add('-- generated by run-tests.ps1 - do not edit')
$parts.Add((Get-Content -LiteralPath (Join-Path $tests 'stub.luau') -Raw))

foreach ($m in $modules) {
  $path = Join-Path $root (Join-Path 'src' $m)
  if (-not (Test-Path $path)) { throw "missing module: $m" }
  $parts.Add("`n-- >>> $m")
  $parts.Add((Get-Content -LiteralPath $path -Raw))
}

$parts.Add("`n-- >>> tests/spec.luau")
$parts.Add((Get-Content -LiteralPath (Join-Path $tests 'spec.luau') -Raw))

$outDir = Join-Path $tests '.build'
if (-not (Test-Path $outDir)) { New-Item -ItemType Directory -Path $outDir | Out-Null }
$suite = Join-Path $outDir 'suite.luau'

$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($suite, ($parts -join "`n"), $utf8)

Write-Host ("luau: {0}" -f $luau)
Write-Host ("suite: {0:N0} bytes from {1} modules" -f (Get-Item $suite).Length, $modules.Count)
Write-Host ""

& $luau $suite
if ($LASTEXITCODE -ne 0) { throw "tests failed" }
